"use strict";
const assert=require("node:assert/strict");
const {axisMap,calibrateDimension,projectAxisCandidates}=require("../src/ai-pdf-axis-projection");
assert.deepEqual(axisMap(null,"x"),{});
assert.deepEqual(axisMap({x:{"1":0,"2":45000,"3":null,"4":""}},"x"),{"1":0,"2":45000});
assert.deepEqual(axisMap({axes_x:["1","2","3","4"],x_spans_mm:[45000,30000,60000]},"x"),{"1":0,"2":45000,"3":75000,"4":135000});
assert.deepEqual(axisMap({axes_y:["А","Б","В"],y_spans_mm:[6000,9000]},"y"),{"А":0,"Б":6000,"В":15000});
assert.deepEqual(axisMap({axes_x:["1","2"],x_spans_mm:[0]},"x"),{});
const x=calibrateDimension([{dimension:"x",value:"1",point:{x:10,y:0}},{dimension:"x",value:"2",point:{x:110,y:0}}],{"1":0,"2":45000},"x");
assert.equal(x.calibrated,true);
assert.equal(x.scaleMmPerPt,450);
assert.deepEqual(axisMap({axes_x:["1","2","2"],x_spans_mm:[45000,45000]},"x"),{});
assert.deepEqual(axisMap({axes_x:["1","2"],x_spans_mm:[""]},"x"),{});
assert.deepEqual(axisMap({axes_x:["1","2"],x_spans_mm:[null]},"x"),{});
assert.deepEqual(axisMap({axes_y:["А","Б","В","Г"],y_spans_mm:[6000,9000,7500]},"y"),{"А":0,"Б":6000,"В":15000,"Г":22500});
const uncalibrated=projectAxisCandidates({observations:[],spatialAssociations:[{mark:"К62",pdfPoint:{x:10,y:20}}]},null);
assert.equal(uncalibrated.fullyCalibrated,false);
assert.equal(uncalibrated.placements[0].xMm,null);
assert.equal(uncalibrated.placements[0].yMm,null);
assert.equal(uncalibrated.safeForAutoPlacement,false);
const {intersections,intersectionEvidence}=require("../src/ai-pdf-intersection-evidence");
const segments=[{x1:NaN,y1:0,x2:1,y2:1},{x1:0,y1:50,x2:100,y2:50},{x1:50,y1:0,x2:50,y2:100}];
assert.deepEqual(intersections(segments)[0].segmentIds,[1,2]);
const geometry={page:1,coordinateSystem:"viewport_points_top_left",heightPt:100,segments};
const page={page:1,heightPt:100,rotation:0};
const vector=intersectionEvidence({page,geometry,candidates:[{mark:"К62",pdfX:50,pdfY:50},{mark:"К63",pdfX:"",pdfY:50}]});
assert.equal(vector.marks[0].nearbyIntersections.length,1);
assert.equal(vector.marks[1].nearbyIntersections.length,0);
assert.equal(intersectionEvidence({page,geometry:{...geometry,heightPt:null}}).geometryAligned,false);
const {analyzeSheet}=require("../src/ai-pdf-sheet-analysis");
const summary=analyzeSheet({page:{page:1,heightPt:100,rotation:0,fragments:[]},geometry,registerMarks:["К62"]});
assert.equal(summary.anchorSummary.total,summary.candidates.length);
assert.equal(summary.anchorSummary.unverified,summary.candidates.length);
assert.equal(summary.anchorSummary.proposed+summary.anchorSummary.ambiguous+summary.anchorSummary.missing<=summary.anchorSummary.total,true);
assert.equal(summary.safeForAutoPlacement,false);
const {summarizeSheets}=require("../src/ai-pdf-sheet-analysis");
assert.deepEqual(summarizeSheets([{anchorSummary:{total:2,proposed:1,ambiguous:1,missing:0,unverified:2}},{anchorSummary:{total:3,proposed:2,ambiguous:0,missing:1,unverified:3}}]),{sheets:2,total:5,proposed:3,ambiguous:1,missing:1,unverified:5,unavailable:0,classified:0,unclassified:0,uniqueMarks:0});
const {elevationEvidence}=require("../src/ai-pdf-elevation-evidence");
const levelReview=elevationEvidence({spatialAssociations:[{mark:"K62",pdfPoint:{x:10,y:10}}],observations:[{kind:"elevation",text:"низ +0.000",valueMm:0,point:{x:10,y:10}},{kind:"elevation",text:"верх +6.000",valueMm:6000,point:{x:12,y:10}}]});
assert.equal(levelReview[0].levelReview.status,"explicit_pair_unverified");
assert.equal(levelReview[0].z0Mm,null);
assert.equal(levelReview[0].z1Mm,null);
const sharedLevels=elevationEvidence({spatialAssociations:[{mark:"K62",pdfPoint:{x:10,y:10}},{mark:"K63",pdfPoint:{x:20,y:10}}],observations:[{kind:"elevation",text:"низ +0.000",valueMm:0,fragmentIndex:1,point:{x:15,y:10}},{kind:"elevation",text:"верх +6.000",valueMm:6000,fragmentIndex:2,point:{x:15,y:12}}]});
assert.equal(sharedLevels[0].levelReview.sharedElevationEvidence,true);
assert.notEqual(sharedLevels[0].levelReview.status,"explicit_pair_unverified");
assert.equal(sharedLevels[0].z0Mm,null);
const unavailable=analyzeSheet({page:{page:1,heightPt:100,rotation:0,fragments:[{str:"К62",x:20,y:20}]},geometry:null,registerMarks:["К62"]});
assert.equal(unavailable.anchorSummary.unavailable,unavailable.candidates.length);
assert.equal(unavailable.anchorSummary.missing,0);
const pair=elevationEvidence({spatialAssociations:[{mark:"K62",pdfPoint:{x:10,y:10}}],observations:[{kind:"elevation",text:"низ +0.000",valueMm:0,point:{x:10,y:10}},{kind:"elevation",text:"верх +6.000",valueMm:6000,point:{x:11,y:10}}]});
