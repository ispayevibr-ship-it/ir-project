assert.equal(registered.candidates[0].structuralType.type,"column");
const alternate=analyzeSheet({page:{page:1,heightPt:100,fragments:[{str:"К62",x:20,y:20}]},registerMarks:[{marking:"К62",mark_description:"Колонна К62"}]});
