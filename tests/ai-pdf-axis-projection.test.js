const {classifyMarkType}=require("../src/ai-pdf-sheet-analysis");
assert.equal(classifyMarkType("Колонна К62").type,"column");
assert.equal(classifyMarkType("Балка Б1").type,"beam");
assert.equal(classifyMarkType("Связь С1").type,"brace");
