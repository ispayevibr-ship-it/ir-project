const manyMarks=["К62","К63","К64","К65","К66","К67","Б1","С1","П1","Ф1"];
const manyRegister=manyMarks.map((mark,i)=>({mark,name:(i<6?"Колонна ":i===6?"Балка ":i===7?"Связь ":i===8?"Прогон ":"Фахверк ")+mark}));
const manyPage={page:2,heightPt:200,rotation:0,fragments:manyMarks.map((mark,i)=>({str:mark,x:20+i*15,y:50}))};
const manyResult=analyzeSheet({page:manyPage,registerMarks:manyRegister});
assert.equal(manyResult.candidates.length,manyMarks.length);
assert.equal(manyResult.candidates.filter(x=>x.structuralType.type==="column").length,6);
assert.equal(manyResult.candidates.every(x=>x.verification==="required"),true);
assert.equal(summarizeSheets([manyResult]).classified,10);
assert.equal(summarizeSheets([manyResult]).unclassified,0);
assert.equal(summarizeSheets([manyResult]).uniqueMarks,10);
const repeatedPage={page:3,heightPt:200,rotation:0,fragments:[
 {str:"К62",x:20,y:50},{str:"К62",x:40,y:50},{str:"К63",x:60,y:50},
 {str:"НЕИЗВЕСТНАЯ",x:80,y:50}]};
const repeated=analyzeSheet({page:repeatedPage,registerMarks:[
 {mark:"К62",name:"Колонна К62"},{mark:"К63",name:"Колонна К63"}]});
assert.equal(repeated.candidates.length,3);
assert.equal(summarizeSheets([repeated]).uniqueMarks,2);
assert.equal(repeated.candidates.filter(x=>x.mark==="К62").length,2);
assert.equal(repeated.candidates.every(x=>x.structuralType.type==="column"),true);
assert.equal(repeated.candidates.every(x=>x.safeForAutoPlacement===false),true);
const {reconcileMarkCounts}=require("../src/ai-pdf-sheet-analysis");
const quantities=reconcileMarkCounts([repeated],[{mark:"К62",quantity:3},{mark:"К63",quantity:1},{mark:"К64",quantity:2},{mark:"К65"}]);
assert.equal(quantities.marks[0].missing,1);
assert.equal(quantities.marks[1].status,"matched");
assert.equal(quantities.marks[2].missing,2);
assert.equal(quantities.marks[3].status,"quantity_unknown");
assert.equal(quantities.safeForAutoPlacement,false);
const duplicates=reconcileMarkCounts([repeated],[{mark:"К62",quantity:2},{mark:"К62",quantity:2}]);
assert.equal(duplicates.marks[1].status,"duplicate_register_mark");
assert.equal(duplicates.marks[0].detected,2);
assert.equal(duplicates.marks[1].detected,2);
const commaQuantity=reconcileMarkCounts([repeated],[{mark:"К62",quantity:"2,0"}]);
assert.equal(commaQuantity.marks[0].status,"matched");
const extra=reconcileMarkCounts([repeated],[{mark:"К62",quantity:1},{mark:"К63",quantity:1}]);
assert.equal(extra.marks[0].status,"excess");
assert.equal(extra.marks[0].excess,1);
