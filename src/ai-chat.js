"use strict";
/*
 * IR Project AI: the engineer's chat with Claude (the development session that changes the program) inside the
 * program. A message — the text, what is on the screen (a screenshot of the window) and the element selected on the
 * montage scheme — goes to that session by itself, with nothing to set up: one commit into chat/<computer>/ of the chat
 * branch with the program's GitHub key (src/ai-github-sync.js), whose check wakes the session. A key of the task
 * «Чат IR Project» (claude.ai, its API trigger), when one was pasted, sends it there instead.
 * The screenshot is kept on this computer (userData/ai-learned/chat/<id>.jpg) and goes with the message.
 * Claude answers in three places:
 *  - chat/<computer>/claude.json of the chat branch — read here every half a minute or so;
 *  - userData/ai-learned/chat/claude.json — the answer written by Claude onto this computer, at once;
 *  - knowledge/chat/journal.json of the update — the journal of fixes made by the engineers' messages (what was asked,
 *    what was changed, which rule), shown in the chat by the message it answers and on the «Журнал» page.
 * Kept in userData/ai-learned/chat/chat.json, so nothing is lost when the internet is down: a message that did not go
 * stays marked and is sent again by «Повторить» (or by itself once the chat can send).
 */
const fs=require("node:fs"),path=require("node:path"),os=require("node:os"),crypto=require("node:crypto");
const BETA="experimental-cc-routine-2026-04-01";
const APP_KNOWLEDGE=path.join(__dirname,"..","knowledge","chat");
// The attribution line under Claude's texts is not shown in the chat.
const footer=t=>String(t||"").replace(/\n+---\s*\n+_Generated by \[Claude Code\]\([^)]*\)_\s*$/u,"").trim();
function createChat({getUserDataPath,safeStorage,fetch:doFetch=globalThis.fetch,version=()=>"",appDir=APP_KNOWLEDGE,computer=()=>os.hostname(),github=null,now=()=>Date.now()}){
 const dir=()=>path.join(getUserDataPath(),"ai-learned","chat");
 const file=()=>path.join(dir(),"chat.json");
 const json=f=>{try{return JSON.parse(fs.readFileSync(f,"utf8"))}catch{return null}};
 function read(){const d=json(file())||{};return{messages:[],seen:"",...d,messages:Array.isArray(d.messages)?d.messages:[]}}
 function write(d){fs.mkdirSync(dir(),{recursive:true});const tmp=file()+".tmp";fs.writeFileSync(tmp,JSON.stringify(d,null,1),"utf8");fs.renameSync(tmp,file())}
 const shotFile=id=>path.join(dir(),String(id).replace(/[^a-z0-9-]/gi,"")+".jpg");
 // Where the messages go: the task's address comes with the update (knowledge/chat/link.json), the key is this computer's.
 // An engineer with a Claude account of his own pastes the address of his own task too: it is kept on this computer.
 const linkFile=()=>path.join(dir(),"link.json");
 const target=()=>{const t=json(path.join(appDir,"link.json"))||{},own=json(linkFile())||{};return own.fire_url?{...t,fire_url:own.fire_url,own:true}:t};
 const encryption=()=>Boolean(safeStorage?.isEncryptionAvailable?.());
 function key(){
  const d=json(linkFile());if(!d?.key)return"";
  if(d.plain)return String(d.key);
  if(!encryption())throw Error("Шифрование Windows недоступно — ключ чата не может быть прочитан");
  return safeStorage.decryptString(Buffer.from(d.key,"base64"))
 }
 // The journal of fixes is data of the drawings: from the closed repository when it came, else from the update.
 const journalFile=()=>appDir===APP_KNOWLEDGE?require("./ai-knowledge-dirs").file("chat/journal.json"):path.join(appDir,"journal.json");
 const viaGithub=()=>{try{return Boolean(github?.chatReady?.())}catch{return false}};
 function link(){const t=target(),d=json(linkFile())||{},key=Boolean(d.key&&t.fire_url),gh=viaGithub();return{connected:key||gh,github:gh,hasKey:Boolean(d.key),fireUrl:t.fire_url||"",own:Boolean(t.own),task:t.task||"Чат IR Project",page:t.page||"https://claude.ai/code/routines",since:d.at||""}}
 // Claude's answers: from the chat branch, the file Claude wrote onto this computer and the journal of the update, once each.
 const branchFile=()=>path.join(dir(),"claude-branch.json");
 function answers(){
  const journal=json(journalFile());
  const out=[];
  for(const own of[json(path.join(dir(),"claude.json")),json(branchFile())])
   for(const m of Array.isArray(own?.messages)?own.messages:[])if(m&&m.id&&m.text&&!out.some(o=>o.id==="c-"+m.id))out.push({id:"c-"+m.id,from:"claude",at:m.at||"",text:footer(m.text),reply_to:m.reply_to||""});
  for(const e of Array.isArray(journal?.entries)?journal.entries:[])if(e&&e.id&&e.text&&e.reply_to)out.push({id:"j-"+e.id,from:"claude",at:e.at||"",text:footer(e.text),reply_to:e.reply_to,version:e.version||"",journal:true});
  return out
 }
 function merged(d){
  const have=new Set(d.messages.map(m=>m.id)),mine=new Set(d.messages.filter(m=>m.from==="user").map(m=>m.id)),seenReply=new Set();
  const list=d.messages.slice();
  for(const a of answers()){
   // A journal entry answers a message of this computer; the same answer written onto the computer is shown once.
   if(a.journal&&!mine.has(a.reply_to))continue;
   const twin=a.journal?list.some(m=>m.from==="claude"&&!m.journal&&m.reply_to===a.reply_to):false;
   if(have.has(a.id)||twin)continue;have.add(a.id);list.push(a)
  }
  for(const m of list)if(m.from==="claude"&&m.reply_to)seenReply.add(m.reply_to);
  list.sort((x,y)=>String(x.at).localeCompare(String(y.at)));
  return list.map(m=>m.from==="user"&&seenReply.has(m.id)?{...m,answered:true}:m)
 }
 function view(d){
  const messages=merged(d),i=messages.findIndex(m=>m.id===d.seen);
  return{messages:messages.map(({context,...m})=>({...m,context:context||null})),unread:messages.slice(i+1).filter(m=>m.from==="claude").length,link:link()}
 }
 // The screenshot taken just before sending (the chat panel hidden), kept with the message.
 function keepShot(jpg){const id="s"+Date.now().toString(36)+crypto.randomBytes(3).toString("hex");fs.mkdirSync(dir(),{recursive:true});fs.writeFileSync(shotFile(id),jpg);return id}
 function shot(id){try{return"data:image/jpeg;base64,"+fs.readFileSync(shotFile(id)).toString("base64")}catch{return""}}
 const lineOf=c=>{
  if(!c||typeof c!=="object")return[];
  const out=[];
  if(c.page)out.push("Раздел: "+c.page+(c.object?" · объект «"+c.object+"»"+(c.objectId?" (id "+c.objectId+")":""):""));
  const e=c.element;
  if(e)out.push("Элемент: "+[e.mark,e.name,e.profile].filter(Boolean).join(" · ")+(e.axes?" · оси "+e.axes:"")+(e.z?" · отм. "+e.z:"")+
   (e.x!==undefined&&e.x!==""?" · X "+e.x+" Y "+e.y:"")+(e.sheet?" · "+e.sheet:"")+(e.id?" (id "+e.id+")":""));
  if(c.node)out.push("Узел: "+c.node);
  if(c.route)out.push("Окно: "+c.route);
  if(c.user)out.push("Пользователь программы: "+c.user);
  return out
 };
 // The text of the call: what the engineer wrote and everything that goes with it.
 function text(m){
  return["Сообщение из чата программы IR Project",
   "Компьютер: "+computer()+" · программа "+(m.version||"?")+" · "+new Date(m.at).toLocaleString("ru-RU")+" · id "+m.id,
   "",m.text,"",
   ...lineOf(m.context),
   ...(m.shot?["Снимок экрана: %APPDATA%\\ir-project\\ai-learned\\chat\\"+m.shot+".jpg (на этом компьютере)"]:[]),
   "Ответ — в файл %APPDATA%\\ir-project\\ai-learned\\chat\\claude.json (reply_to: "+m.id+")"].join("\n").slice(0,60000)
 }
 async function deliver(m){
  const t=target();let k="";try{k=t.fire_url?key():""}catch(e){if(!viaGithub())throw e}
  if(!k||!t.fire_url){
   // Without a key of the task: one commit on the chat branch, with the screenshot.
   if(viaGithub()){
    let shot="";if(m.shot)try{shot=fs.readFileSync(shotFile(m.shot)).toString("base64")}catch{}
    try{await github.chatPost({id:m.id,text:text(m),shot,repo:t.github_repo,branch:t.github_branch});return{via:"github"}}
    catch(e){throw Error("Нет связи с GitHub — "+String(e.message||e))}
   }
   const x=Error("Чат не подключён: администратор указывает ключ GitHub в настройках ИИ (раздел GitHub)");x.code="no-key";throw x
  }
  let r;
  try{r=await doFetch(t.fire_url,{method:"POST",headers:{Authorization:"Bearer "+k,"anthropic-beta":BETA,"anthropic-version":"2023-06-01","content-type":"application/json"},body:JSON.stringify({text:text(m)})})}
  catch(e){throw Error("Нет связи с claude.ai — проверьте интернет ("+String(e.message||e)+")")}
  if(r.ok){let b={};try{b=await r.json()}catch{}return{session:b.claude_code_session_id||""}}
  let detail="";try{detail=String((await r.json())?.error?.message||"")}catch{}
  if(r.status===401||r.status===403)throw Error("Ключ чата не подходит — создайте новый ключ и вставьте его вверху чата"+(detail?" ("+detail+")":""));
  if(r.status===429)throw Error("Слишком много сообщений за час (до 30) — отправьте позже кнопкой «Повторить»");
  throw Error("claude.ai ответил "+r.status+(detail?": "+detail:""))
 }
 async function send({text:body,context,shotId}={}){
  body=String(body||"").trim().slice(0,8000);if(!body)throw Error("Пустое сообщение");
  const d=read(),m={id:"m"+Date.now().toString(36)+crypto.randomBytes(2).toString("hex"),from:"user",at:new Date().toISOString(),text:body,
   context:context&&typeof context==="object"?JSON.parse(JSON.stringify(context)):null,shot:shotId&&fs.existsSync(shotFile(shotId))?shotId:"",version:version(),state:"sending"};
  d.messages.push(m);d.seen=m.id;write(d);
  return finish(m.id)
 }
 async function finish(id){
  const d=read(),m=d.messages.find(x=>x.id===id);if(!m)throw Error("Сообщение не найдено");
  const set=patch=>{const a=read(),x=a.messages.find(y=>y.id===id);if(x){Object.assign(x,patch);if(patch.state==="sent")delete x.error}write(a)};
  try{const r=await deliver(m);set({state:"sent",sentAt:new Date().toISOString(),...(r.session?{session:r.session}:{})})}
  catch(e){set({state:e.code==="no-key"?"waiting":"error",error:String(e.message||e)})}
  return view(read())
 }
 const retry=({id}={})=>finish(String(id||""));
 // The key from the task's API trigger, kept encrypted (Windows DPAPI); the messages that waited for it go at once.
 const FIRE=/^https:\/\/api\.anthropic\.com\/v1\/claude_code\/routines\/trig_[A-Za-z0-9]{8,}\/fire$/;
 async function setLink({key:k,url}={}){
  k=String(k||"").trim();url=String(url||"").trim();
  if(url&&!FIRE.test(url))throw Error("Это не адрес задачи: он вида https://api.anthropic.com/v1/claude_code/routines/trig_…/fire (Fire URL в задаче)");
  if(!/^sk-ant-[A-Za-z0-9_-]{20,}$/.test(k))throw Error("Это не ключ чата: он начинается с sk-ant- (кнопка «Generate token» в задаче «Чат IR Project»)");
  if(!encryption())throw Error("Шифрование Windows недоступно — ключ не сохраняется открытым текстом");
  fs.mkdirSync(dir(),{recursive:true});
  fs.writeFileSync(linkFile(),JSON.stringify({key:safeStorage.encryptString(k).toString("base64"),...(url?{fire_url:url}:{}),at:new Date().toISOString()}),"utf8");
  const waiting=merged(read()).filter(m=>m.from==="user"&&!m.answered&&(m.state==="waiting"||m.state==="error"));
  for(const m of waiting)await finish(m.id);
  return view(read())
 }
 function clearLink(){try{fs.rmSync(linkFile(),{force:true})}catch{}return view(read())}
 function list(){return view(read())}
 // Claude's answers from the chat branch (at most every 30 s), and the messages that waited for a way to go.
 let fetched=0,sending=null;
 async function sync(){
  if(viaGithub()&&now()-fetched>=30e3){
   fetched=now();
   try{const t=target(),a=await github.chatAnswers({repo:t.github_repo,branch:t.github_branch});if(a&&Array.isArray(a.messages)){fs.mkdirSync(dir(),{recursive:true});fs.writeFileSync(branchFile(),JSON.stringify(a),"utf8")}}catch{}
  }
  if(link().connected&&!sending){
   const waiting=merged(read()).filter(m=>m.from==="user"&&!m.answered&&m.state==="waiting");
   if(waiting.length)sending=(async()=>{for(const m of waiting)await finish(m.id)})().finally(()=>{sending=null});
   if(sending)await sending
  }
  return view(read())
 }
 function markSeen(){const d=read(),all=merged(d),last=all[all.length-1];if(last){d.seen=last.id;write(d)}return view(d)}
 // The journal of fixes for the «Журнал» page: every entry of the update, newest first.
 function journal(){const j=json(journalFile());return{entries:(Array.isArray(j?.entries)?j.entries:[]).filter(e=>e&&e.id).slice().sort((a,b)=>String(b.at).localeCompare(String(a.at)))}}
 return{list,send,retry,sync,markSeen,keepShot,shot,link,setLink,clearLink,journal,text}
}
module.exports={createChat,footer,BETA};
